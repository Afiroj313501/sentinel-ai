import { useEffect, useRef, useState } from "react";
import { AlertTriangle, Check, Copy, Download, RefreshCw, Wrench } from "lucide-react";
import { fetchFix, suggestFix } from "../../services/fixes";
import { formatDate } from "../../services/format";
import type { FixSuggestion } from "../../types/fix";
import DiffView from "./DiffView";

type PanelState =
  | { kind: "checking" }
  | { kind: "idle" }
  | { kind: "generating"; previous: FixSuggestion | null }
  | { kind: "ready"; fix: FixSuggestion }
  | { kind: "error"; message: string; previous: FixSuggestion | null };

type CopyState = "idle" | "copied" | "failed";

function downloadPatch(diff: string, filePath: string) {
  const base = filePath.split("/").pop() ?? "fix";
  const safe = base.replace(/[^A-Za-z0-9._-]/g, "_") || "fix";
  const url = URL.createObjectURL(new Blob([diff], { type: "text/plain" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = `sentinel-fix-${safe}.patch`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}

/** Model output is untrusted: it is only ever rendered as plain text. */
function FixBody({ fix }: { fix: FixSuggestion }) {
  const [copyState, setCopyState] = useState<CopyState>("idle");
  const timer = useRef<number | undefined>(undefined);

  useEffect(() => () => window.clearTimeout(timer.current), []);

  async function copyPatch(diff: string) {
    try {
      await navigator.clipboard.writeText(diff);
      setCopyState("copied");
    } catch {
      setCopyState("failed");
    }
    window.clearTimeout(timer.current);
    timer.current = window.setTimeout(() => setCopyState("idle"), 2500);
  }

  const footer = (
    <>
      <p className="fine-print" style={{ margin: 0 }}>
        Generated by {fix.provider} / {fix.model} on {formatDate(fix.created_at)}
      </p>
      <p className="fine-print" style={{ margin: 0, fontStyle: "italic" }}>
        {fix.notice}
      </p>
    </>
  );

  if (!fix.can_fix || !fix.diff) {
    return (
      <div className="ai-body">
        <div className="alert alert-info">
          <span>
            <strong>The AI did not propose a patch.</strong> {fix.rationale}
          </span>
        </div>
        {footer}
      </div>
    );
  }

  const diff = fix.diff;
  return (
    <div className="ai-body">
      <p className="alert alert-warn">
        <span style={{ display: "flex", gap: 8 }}>
          <AlertTriangle size={15} aria-hidden="true" style={{ flexShrink: 0 }} />
          <span>
            <strong>Untested. Review before use.</strong> This patch has not been applied, compiled,
            or run, and it was written from a short code excerpt.
          </span>
        </span>
      </p>

      <div>
        <p className="label">Why this change</p>
        <p className="body-text">{fix.rationale}</p>
      </div>

      <div>
        <p className="label">
          Proposed patch Â· <span className="mono" style={{ textTransform: "none" }}>{fix.file_path}</span>
        </p>
        <DiffView diff={diff} />
      </div>

      <div className="toolbar">
        <button type="button" className="btn btn-ghost btn-sm" onClick={() => void copyPatch(diff)}>
          {copyState === "copied" ? <Check aria-hidden="true" /> : <Copy aria-hidden="true" />}
          {copyState === "copied" ? "Copied" : "Copy patch"}
        </button>
        <button
          type="button"
          className="btn btn-ghost btn-sm"
          onClick={() => downloadPatch(diff, fix.file_path)}
        >
          <Download aria-hidden="true" />
          Download .patch
        </button>
        {copyState === "failed" && (
          <span role="status" className="small muted">
            Copy failed. Select the patch text manually instead.
          </span>
        )}
      </div>

      <p className="fine-print" style={{ margin: 0 }}>
        {fix.syntax_check === "passed"
          ? "The patched excerpt parses as valid Python. This does not prove the fix works."
          : "Syntax was not checked for this file type."}{" "}
        To apply it yourself, run <span className="mono">git apply --check</span> on the downloaded
        file from your repository root, review the result, then apply it. Sentinel never changes your
        code.
      </p>
      {footer}
    </div>
  );
}

export default function FixPanel({ findingId }: { findingId: string }) {
  const [state, setState] = useState<PanelState>({ kind: "checking" });

  // Show a saved suggestion right away if one exists.
  useEffect(() => {
    const controller = new AbortController();
    fetchFix(findingId, controller.signal)
      .then((fix) => setState(fix ? { kind: "ready", fix } : { kind: "idle" }))
      .catch(() => {
        if (!controller.signal.aborted) setState({ kind: "idle" });
      });
    return () => controller.abort();
  }, [findingId]);

  async function generate(refresh: boolean) {
    const previous =
      state.kind === "ready"
        ? state.fix
        : state.kind === "error" || state.kind === "generating"
          ? state.previous
          : null;
    setState({ kind: "generating", previous });
    try {
      setState({ kind: "ready", fix: await suggestFix(findingId, refresh) });
    } catch (error) {
      setState({
        kind: "error",
        previous,
        message: error instanceof Error ? error.message : "The suggestion could not be generated.",
      });
    }
  }

  const previous = state.kind === "generating" || state.kind === "error" ? state.previous : null;
  const shown = state.kind === "ready" ? state.fix : previous;
  const busy = state.kind === "generating";

  return (
    <section aria-label="Suggested fix" className="fix-panel">
      <div className="ai-head">
        <h3 className="ai-title">
          <Wrench aria-hidden="true" />
          Suggested fix
          <span className="ai-tag">AI-generated Â· untested</span>
        </h3>
        {shown && (
          <button
            type="button"
            className="btn btn-ghost btn-sm"
            disabled={busy}
            onClick={() => void generate(true)}
          >
            <RefreshCw aria-hidden="true" />
            Regenerate
          </button>
        )}
      </div>

      {state.kind === "checking" && (
        <p className="fine-print">Checking for a saved suggestion...</p>
      )}

      {state.kind === "idle" && (
        <div className="ai-stack">
          <p className="small muted" style={{ margin: 0 }}>
            Asks the AI for a small patch, shown as a diff for you to review. It is built from a
            short code excerpt, is never applied automatically, and sends the finding and excerpt to
            your configured AI provider.
          </p>
          <div>
            <button type="button" className="btn btn-primary btn-sm" onClick={() => void generate(false)}>
              <Wrench aria-hidden="true" />
              Suggest a fix
            </button>
          </div>
        </div>
      )}

      {busy && (
        <p role="status" className="small muted" style={{ margin: "10px 0 0" }}>
          Asking the AI model for a patch... local models can take a minute or more. You can keep
          browsing; the result is saved when it finishes.
        </p>
      )}

      {state.kind === "error" && (
        <div role="alert" className="alert alert-error" style={{ marginTop: 10 }}>
          <span>{state.message}</span>
          <button
            type="button"
            className="text-btn"
            onClick={() => void generate(state.previous !== null)}
          >
            Try again
          </button>
        </div>
      )}

      {shown && <FixBody key={shown.created_at} fix={shown} />}
    </section>
  );
}
