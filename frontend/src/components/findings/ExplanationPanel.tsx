import { useEffect, useState } from "react";
import { AlertTriangle, RefreshCw, Sparkles } from "lucide-react";
import { explainFinding, fetchExplanation } from "../../services/explanations";
import { formatDate } from "../../services/format";
import type { Explanation } from "../../types/explanation";

type PanelState =
  | { kind: "checking" }
  | { kind: "idle" }
  | { kind: "generating"; previous: Explanation | null }
  | { kind: "ready"; explanation: Explanation }
  | { kind: "error"; message: string; previous: Explanation | null };

const PRIMARY =
  "inline-flex items-center gap-2 rounded-md bg-indigo-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-indigo-700 disabled:cursor-not-allowed disabled:opacity-50";
const SECONDARY =
  "inline-flex items-center gap-1.5 rounded-md border border-gray-300 bg-white px-2.5 py-1 text-xs font-medium text-gray-700 hover:bg-gray-50 disabled:cursor-not-allowed disabled:opacity-50";

function Section({ title, text }: { title: string; text: string }) {
  return (
    <div>
      <h4 className="text-xs font-semibold uppercase tracking-wide text-gray-500">{title}</h4>
      <p className="mt-1 whitespace-pre-wrap text-gray-800">{text}</p>
    </div>
  );
}

function ExplanationBody({ explanation }: { explanation: Explanation }) {
  return (
    <div className="mt-3 space-y-3">
      {!explanation.evidence_sufficient && (
        <p className="flex items-start gap-2 rounded-md border border-amber-200 bg-amber-50 p-2 text-xs text-amber-900">
          <AlertTriangle className="mt-0.5 h-4 w-4 shrink-0" aria-hidden="true" />
          The AI says the available evidence is not enough to judge this finding reliably.
        </p>
      )}
      <Section title="Summary" text={explanation.summary} />
      <Section title="Likely impact if it is a real issue" text={explanation.impact} />
      <Section title="Suggested remediation" text={explanation.remediation} />
      <p className="text-xs text-gray-500">
        AI confidence: {explanation.confidence} · Generated by {explanation.provider} /{" "}
        {explanation.model} on {formatDate(explanation.created_at)}
      </p>
      <p className="text-xs italic text-gray-500">{explanation.notice}</p>
    </div>
  );
}

export default function ExplanationPanel({ findingId }: { findingId: string }) {
  const [state, setState] = useState<PanelState>({ kind: "checking" });

  useEffect(() => {
    const controller = new AbortController();
    fetchExplanation(findingId, controller.signal)
      .then((explanation) =>
        setState(explanation ? { kind: "ready", explanation } : { kind: "idle" }),
      )
      .catch(() => {
        if (!controller.signal.aborted) setState({ kind: "idle" });
      });
    return () => controller.abort();
  }, [findingId]);

  async function generate(refresh: boolean) {
    const previous =
      state.kind === "ready"
        ? state.explanation
        : state.kind === "error" || state.kind === "generating"
          ? state.previous
          : null;
    setState({ kind: "generating", previous });
    try {
      setState({ kind: "ready", explanation: await explainFinding(findingId, refresh) });
    } catch (error) {
      setState({
        kind: "error",
        previous,
        message: error instanceof Error ? error.message : "The explanation could not be generated.",
      });
    }
  }

  const previous =
    state.kind === "generating" || state.kind === "error" ? state.previous : null;
  const shown = state.kind === "ready" ? state.explanation : previous;
  const busy = state.kind === "generating";

  return (
    <section
      aria-label="AI explanation"
      className="rounded-md border border-indigo-200 bg-indigo-50/50 p-3 text-sm"
    >
      <div className="flex items-center justify-between gap-2">
        <h3 className="flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-indigo-800">
          <Sparkles className="h-4 w-4" aria-hidden="true" />
          AI explanation
          <span className="rounded bg-indigo-100 px-1.5 py-0.5 text-[10px] normal-case">
            AI-generated
          </span>
        </h3>
        {shown && (
          <button type="button" className={SECONDARY} disabled={busy} onClick={() => void generate(true)}>
            <RefreshCw className="h-3.5 w-3.5" aria-hidden="true" />
            Regenerate
          </button>
        )}
      </div>

      {state.kind === "checking" && (
        <p className="mt-2 text-xs text-gray-500">Checking for a saved explanation...</p>
      )}
      {state.kind === "idle" && (
        <div className="mt-2 space-y-2">
          <p className="text-xs text-gray-600">
            Explains what the scanner flagged and how to fix it. This sends the finding and its code
            excerpt to your configured AI provider.
          </p>
          <button type="button" className={PRIMARY} onClick={() => void generate(false)}>
            <Sparkles className="h-4 w-4" aria-hidden="true" />
            Explain with AI
          </button>
        </div>
      )}
      {busy && (
        <p role="status" className="mt-2 text-xs text-gray-600">
          Asking the AI model... local models can take a minute or more. You can keep browsing; the
          result is saved when it finishes.
        </p>
      )}
      {state.kind === "error" && (
        <div role="alert" className="mt-2 rounded-md border border-red-200 bg-red-50 p-2 text-xs text-red-800">
          <p>{state.message}</p>
          <button type="button" className="mt-1 font-medium underline" onClick={() => void generate(state.previous !== null)}>
            Try again
          </button>
        </div>
      )}
      {shown && <ExplanationBody explanation={shown} />}
    </section>
  );
}
